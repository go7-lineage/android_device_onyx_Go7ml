#!/usr/bin/env bash
# Generate vendor/onyx/Go7ml (firmware the mainline kernel loads, plus the panel's waveform) from stock files.
# usage: setup-firmware.sh ANDROID_TOP STOCK_VENDOR_FIRMWARE MODEM_IMAGE_DIR BT_IMAGE_DIR WAVEFORM STOCK_SENSORS
#   e.g. stock-extract/vendor_a/firmware stock-extract/modem_image stock-extract/bt_image
#        stock-extract/system_a/waveform/eink_waveform.wbf stock-extract/vendor_a/etc/sensors   (kernel.md T-FW1)
# Needs kernel/mainline/firmware/pack.py from the port's work tree (PACK=...), and linux-firmware for
# ath10k firmware-5.bin (LINUX_FIRMWARE=.../lib/firmware).
set -euo pipefail
top=$1 vend=$2 modem=$3 bt=$4 wbf=$5 sensors=$6
PACK=${PACK:-kernel/mainline/firmware/pack.py}
out=$top/vendor/onyx/Go7ml
rm -rf "$out"
mkdir -p "$out/proprietary/vendor/firmware"
python3 "$PACK" "$out/proprietary/vendor/firmware" "$vend" "$modem" "$bt"
# the e-ink driver requests eink_waveform.wbf (firmware_class.path=/vendor/firmware)
cp "$wbf" "$out/proprietary/vendor/firmware/eink_waveform.wbf"
mkdir -p "$out/proprietary/vendor/etc/hexagonrpcd-root/sensors/config"
cp "$sensors"/config/*.json "$out/proprietary/vendor/etc/hexagonrpcd-root/sensors/config/"
cp "$sensors/sns_reg_config" "$out/proprietary/vendor/etc/hexagonrpcd-root/sensors/sns_reg.conf"
{
    echo "# Generated by device/onyx/Go7ml/setup-firmware.sh"
    echo "PRODUCT_COPY_FILES += \\"
    (cd "$out/proprietary" && find vendor -type f | sort) | while read -r f; do
        echo "    vendor/onyx/Go7ml/proprietary/$f:\$(TARGET_COPY_OUT_VENDOR)/${f#vendor/} \\"
    done
    echo
} > "$out/Go7ml-vendor.mk"
echo "$out: $(find "$out/proprietary" -type f | wc -l) files"
